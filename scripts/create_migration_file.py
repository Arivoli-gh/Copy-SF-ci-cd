#!/usr/bin/env python3
"""
create_migration_file.py

Reads the DDL of a Snowflake object, replaces the database name with the
schemachange variable {{ DATABASE }}, picks the next free versioned file name
(V<next>__deployment<YYYYMMDD>.sql, e.g. V1.0.5__deployment20261124.sql) and puts the file into a
Snowflake workspace (the live version, so it shows up as an added file in the
Git workspace, ready to commit and push).

Examples
  # preview only (nothing is written)
  python create_migration_file.py DEMO_DEV.APP.CUSTOMER_ORDERS \
      --workspace 'USER$.PUBLIC."snowflake-cicd-poc"' --dry-run

  # create the file in the workspace, folder "migrations"
  python create_migration_file.py DEMO_DEV.APP.CUSTOMER_ORDERS \
      --workspace 'USER$.PUBLIC."snowflake-cicd-poc"' --folder migrations

  # function or procedure: pass the argument types
  python create_migration_file.py "DEMO_DEV.APP.MY_PROC(VARCHAR, NUMBER)" --workspace ...

Connection: uses a connection from ~/.snowflake/connections.toml
(--connection NAME, or the default connection). The role needs access to the
object (GET_DDL) and WRITE on the workspace. Requires snowflake-connector-python.
"""
import argparse
import datetime
import os
import re
import sys
import tempfile
from pathlib import Path

# Object types tried (in this order) when --type is not given.
TYPES = ["DYNAMIC_TABLE", "ICEBERG_TABLE", "EVENT_TABLE", "VIEW", "TABLE",
         "STREAM", "TASK", "SEQUENCE", "PIPE", "FILE_FORMAT"]
ROUTINE_TYPES = ["FUNCTION", "PROCEDURE"]   # used when the name has a (signature)
# Objects that hold data or state: CREATE OR REPLACE would wipe them, so the
# generated script uses CREATE ... IF NOT EXISTS instead.
STATEFUL = {"TABLE", "DYNAMIC_TABLE", "ICEBERG_TABLE", "EVENT_TABLE", "SEQUENCE", "STREAM"}

VERSION_RE = re.compile(r"^V(\d+(?:\.\d+)*)__", re.I)
STATEFUL_CREATE_RE = re.compile(
    r"^\s*create\s+or\s+replace\s+"
    r"((?:(?:transient|temporary|temp|volatile|local|global|hybrid|dynamic|iceberg|event|external)\s+)*"
    r"(?:table|sequence|stream))\s+(?!if\s+not\s+exists)", re.I)


# ----------------------------------------------------------------- parsing
def split_name(full):
    """'DB.SCHEMA.OBJ' or 'DB.SCHEMA.FUNC(VARCHAR)' -> ([db, schema, obj], signature)."""
    sig, in_q = "", False
    for i, ch in enumerate(full):
        if ch == '"':
            in_q = not in_q
        elif ch == "(" and not in_q:
            sig, full = full[i:].strip(), full[:i]
            break
    parts, cur, in_q = [], "", False
    for ch in full:
        if ch == '"':
            in_q = not in_q
            cur += ch
        elif ch == "." and not in_q:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    parts.append(cur.strip())
    if len(parts) != 3 or not all(parts):
        raise ValueError("Object name must be fully qualified: DATABASE.SCHEMA.OBJECT")
    return parts, sig


def slug(text):
    return re.sub(r"[^0-9a-z]+", "_", text.replace('"', "").lower()).strip("_")


# ----------------------------------------------------------------- versions
def _key(v):
    return v + [0] * (6 - len(v))


def highest_version(file_names):
    best = None
    for name in file_names:
        m = VERSION_RE.match(os.path.basename(name.replace("\\", "/")))
        if m:
            v = [int(x) for x in m.group(1).split(".")]
            if best is None or _key(v) > _key(best):
                best = v
    return best


def next_version(file_names, bump="patch"):
    best = highest_version(file_names)
    if best is None:
        return "1.0.0"
    v = (best + [0, 0, 0])[:max(3, len(best))]
    if bump == "major":
        v = [v[0] + 1, 0, 0]
    elif bump == "minor":
        v = [v[0], v[1] + 1, 0]
    else:
        v[2] += 1
    return ".".join(str(x) for x in v)


# ----------------------------------------------------------------- DDL
def make_safe(ddl, obj_type):
    """Stateful objects: CREATE OR REPLACE -> CREATE ... IF NOT EXISTS."""
    if obj_type in STATEFUL:
        return STATEFUL_CREATE_RE.sub(lambda m: "CREATE " + m.group(1).upper() + " IF NOT EXISTS ", ddl, count=1)
    return ddl


def parameterize(ddl, database, var="DATABASE"):
    """Replace DATABASE. (quoted or not) with {{ DATABASE }}. -> (new_ddl, count)."""
    if database.startswith('"'):
        pat = re.compile(r"(?<![\w$.])" + re.escape(database) + r"(?=\s*\.)")
    else:
        pat = re.compile(r'(?<![\w$.])"?' + re.escape(database) + r'"?(?=\s*\.)', re.I)
    return pat.subn("{{ %s }}" % var, ddl)


def build_content(fq_name, obj_type, ddl, parts, var="DATABASE", add_schema=True):
    db, schema, _ = parts
    safe = make_safe(ddl.strip(), obj_type)
    body, count = parameterize(safe, db, var)
    ref = "{{ %s }}" % var
    lines = [
        "-- Generated by create_migration_file.py",
        "-- Source object : %s (%s)" % (fq_name, obj_type),
        "-- Generated on  : %s" % datetime.datetime.now().strftime("%Y-%m-%d %H:%M"),
        "-- The database name is the schemachange variable %s (passed with --vars)." % ref,
        "",
    ]
    if add_schema:
        lines += ["CREATE SCHEMA IF NOT EXISTS %s.%s;" % (ref, schema), ""]
    body = body.rstrip()
    if not body.endswith(";"):
        body += "\n;"          # own line, in case the DDL ends with a -- comment
    lines += [body, ""]
    warnings = []
    if count == 0:
        warnings.append("Database name %s was not found in the DDL; check that the script is portable." % db)
    if any(tok in ddl for tok in ("{{", "{%", "{#")):
        warnings.append("The DDL contains Jinja markers ({{, {% or {#); schemachange will try to render them.")
    return "\n".join(lines), count, warnings


# ----------------------------------------------------------------- Snowflake calls
def fetch_ddl(cur, fq_name, obj_type=None):
    candidates = [obj_type.upper()] if obj_type else (ROUTINE_TYPES if "(" in fq_name else TYPES)
    errors = []
    for t in candidates:
        try:
            cur.execute("SELECT GET_DDL(%s, %s, TRUE)", (t, fq_name))
            return t, cur.fetchone()[0]
        except Exception as exc:  # wrong type or no access: try the next one
            errors.append("%s: %s" % (t, str(exc).splitlines()[0]))
    raise RuntimeError("Could not get DDL for %s.\n  %s" % (fq_name, "\n  ".join(errors)))


def list_workspace_files(cur, workspace):
    try:  # make sure a live (editable) version exists; ignore if it already does
        cur.execute("ALTER WORKSPACE %s ADD LIVE VERSION FROM LAST" % workspace)
    except Exception:
        pass
    last = None
    for ver in ("live", "head"):
        try:
            cur.execute("LIST 'snow://workspace/%s/versions/%s/'" % (workspace, ver))
            if ver == "head":
                print("WARNING: could not read the live version; version numbers were taken "
                      "from the published (head) version only.", file=sys.stderr)
            return [row[0] for row in cur.fetchall()]
        except Exception as exc:
            last = exc
    raise RuntimeError("Cannot list workspace files: %s" % last)


def put_file(cur, local_path, workspace, folder):
    target = "snow://workspace/%s/versions/live/%s" % (workspace, folder.strip("/") + "/" if folder.strip("/") else "")
    cur.execute("PUT '%s' '%s' AUTO_COMPRESS=FALSE OVERWRITE=FALSE" % (Path(local_path).as_uri(), target))
    return cur.fetchall(), target


# ----------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser(description="Create a schemachange versioned file from a Snowflake object's DDL.")
    ap.add_argument("object", help="Fully qualified name DB.SCHEMA.OBJECT (functions/procedures: add the argument types)")
    ap.add_argument("--workspace", required=True, help='Workspace as DB.SCHEMA."name", e.g. USER$.PUBLIC."my-workspace"')
    ap.add_argument("--folder", default="migrations", help="Folder inside the workspace (default: migrations)")
    ap.add_argument("--type", help="Object type for GET_DDL (default: auto-detect)")
    ap.add_argument("--bump", choices=["patch", "minor", "major"], default="patch", help="Which version part to increase")
    ap.add_argument("--description", help="Full text for the file name after V<version>__ (replaces prefix + date)")
    ap.add_argument("--prefix", default="deployment", help="Text before the date in the file name (default: deployment)")
    ap.add_argument("--date", help="Date tag YYYYMMDD for the file name (default: today, UTC)")
    ap.add_argument("--var-name", default="DATABASE", help="schemachange variable name (default: DATABASE)")
    ap.add_argument("--no-schema", action="store_true", help="Do not add CREATE SCHEMA IF NOT EXISTS")
    ap.add_argument("--connection", help="Connection name in connections.toml (default connection if omitted)")
    ap.add_argument("--dry-run", action="store_true", help="Print the file name and content only")
    ap.add_argument("--save-to", help="Write the file to this local folder instead of the workspace")
    args = ap.parse_args()

    if args.date and not re.fullmatch(r"\d{8}", args.date):
        ap.error("--date must be YYYYMMDD, for example 20261124")
    if not re.fullmatch(r"[A-Za-z0-9_]*", args.prefix):
        ap.error("--prefix may contain only letters, digits and underscores")

    parts, sig = split_name(args.object)
    import snowflake.connector
    conn = snowflake.connector.connect(connection_name=args.connection) if args.connection else snowflake.connector.connect()
    try:
        cur = conn.cursor()
        obj_type, ddl = fetch_ddl(cur, args.object, args.type)
        content, count, warnings = build_content(args.object, obj_type, ddl, parts, args.var_name, not args.no_schema)
        files = list_workspace_files(cur, args.workspace)
        version = next_version(files, args.bump)
        date_tag = args.date or datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d")
        desc = slug(args.description) if args.description else "%s%s" % (args.prefix, date_tag)
        file_name = "V%s__%s.sql" % (version, desc)

        print("Object   : %s (%s)" % (args.object, obj_type))
        print("File     : %s/%s" % (args.folder.strip("/"), file_name))
        print("Database references replaced: %d" % count)
        for w in warnings:
            print("WARNING  : " + w, file=sys.stderr)
        if args.dry_run:
            print("\n----- file content -----\n" + content)
            return
        out_dir = args.save_to or tempfile.mkdtemp()
        os.makedirs(out_dir, exist_ok=True)
        local_path = os.path.join(out_dir, file_name)
        with open(local_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        if args.save_to:
            print("Saved locally: " + local_path)
            return
        rows, target = put_file(cur, local_path, args.workspace, args.folder)
        print("Uploaded to %s" % target)
        for r in rows:
            print("  " + " | ".join(str(c) for c in r))
        print("Next: open the workspace, review the added file, then commit and push.")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
