CREATE TABLE IF NOT EXISTS APP.CUSTOMERS (
  CUSTOMER_ID NUMBER AUTOINCREMENT PRIMARY KEY,
  FULL_NAME   VARCHAR(200) NOT NULL,
  EMAIL       VARCHAR(320),
  CREATED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS APP.ORDERS (
  ORDER_ID    NUMBER AUTOINCREMENT PRIMARY KEY,
  CUSTOMER_ID NUMBER NOT NULL,
  AMOUNT      NUMBER(12,2) NOT NULL,
  ORDER_TS    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE VIEW APP.CUSTOMER_ORDERS AS
SELECT c.CUSTOMER_ID, c.FULL_NAME, o.ORDER_ID, o.AMOUNT, o.ORDER_TS
FROM APP.CUSTOMERS c
JOIN APP.ORDERS o ON o.CUSTOMER_ID = c.CUSTOMER_ID;
