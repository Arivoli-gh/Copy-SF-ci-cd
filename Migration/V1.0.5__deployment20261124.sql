
CREATE OR REPLACE VIEW APP.VW_CUSTOMER_ORDER_DETAILS AS
SELECT
  c.CUSTOMER_ID,
  c.FULL_NAME,
  c.EMAIL,
  o.ORDER_ID,
  o.ORDER_TS,
  o.AMOUNT                              AS ORDER_TOTAL_AMOUNT,
  oi.ITEM_ID,
  oi.PRODUCT_NAME,
  oi.QUANTITY,
  oi.UNIT_PRICE,
  (oi.QUANTITY * oi.UNIT_PRICE)         AS LINE_ITEM_TOTAL
FROM APP.CUSTOMERS c
LEFT JOIN APP.ORDERS o
  ON c.CUSTOMER_ID = o.CUSTOMER_ID
LEFT JOIN APP.ORDER_ITEMS oi
  ON o.ORDER_ID = oi.ORDER_ID;